"""Writes docs/medtac-campus-reference.md from the campus build reports:
floor-by-floor room directory, encounter table, loot report and the
existing-asset reuse report. Python standard library only."""
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORTS = ROOT / 'resources/campus/reports'
BUILDINGS = {'lab1': 'Lab 1 Research', 'lab2': 'Lab 2 Clinical', 'distribution_wing': 'Distribution offices (L-wing)', 'distribution': 'Distribution hall'}
FLOORS = {
    'lab1': ['Reception and Administration', 'Pharmaceutical Research Laboratories', 'Restricted Research and Skybridge', 'Advanced Research and Executive Operations'],
    'lab2': ['Intake and Emergency Treatment', 'Patient Care and Observation', 'Clinical Trials and Skybridge', 'Intensive Care and Experimental Treatments'],
    'distribution_wing': ['Dispatch and Staff Facilities', 'Warehouse Offices and Security'],
    'distribution': ['High-bay hall'],
}
TIERS = {1: 'Common', 2: 'Uncommon', 3: 'Rare', 4: 'Very rare'}


def load(name):
    return json.loads((REPORTS / name).read_text(encoding='utf-8'))


def main():
    rooms = load('rooms.json')
    loot = load('loot.json')
    assets = load('assets.json')
    encounters = load('encounters.json')
    validation = load('validation.json')
    catalog = {e['id']: e['name'] for e in json.loads((ROOT / 'resources/environment_props/catalog.json').read_text(encoding='utf-8'))}
    out = ['# MedTac Research Campus reference', '',
           'Generated by `python tools/build_campus_docs.py` from `resources/campus/reports/`. See the [campus guide](medtac-campus.md) for design, pipeline and verification.', '']
    out += ['## Room directory', '']
    by_floor = defaultdict(list)
    for room in rooms['rooms']:
        by_floor[(room['building'], room['floor'])].append(room)
    for building, title in BUILDINGS.items():
        for index, name in enumerate(FLOORS[building]):
            items = by_floor.get((building, index + 1), [])
            if not items:
                continue
            tier = items[0]['tier']
            out += [f'### {title} — level {index + 1}: {name}', '',
                    f'Loot tier {tier} ({TIERS.get(tier, tier)}). {len(items)} rooms, {sum(r["sources"] for r in items)} searchable containers, {sum(r["loose"] for r in items)} loose sockets.', '',
                    '| Room | Function | Area m² | Doors | Storage | Loose |', '| --- | --- | ---: | --- | ---: | ---: |']
            for r in sorted(items, key=lambda r: (r['rect'][1], r['rect'][0])):
                doors = ', '.join(d.replace(':', ' ') for d in r['doors'])
                out.append(f"| {r['name']} | {r['role'].replace('_', ' ')} | {r['area_m2']:.0f} | {doors} | {r['sources']} | {r['loose']} |")
            out.append('')
    out += ['### Exterior and shared areas', '']
    for area in rooms['areas']:
        out.append(f"- {area['name']} ({area['building']}, level {area['floor']})")
    out += ['', '## Encounters', '', '| Building | Level | Infected | Scavengers |', '| --- | ---: | ---: | ---: |']
    counts = defaultdict(lambda: [0, 0])
    for e in encounters:
        counts[(e['building'], e['floor'])][0 if e['kind'] == 'infected' else 1] += 1
    for (building, level), (infected, scav) in sorted(counts.items()):
        out.append(f'| {building} | {level} | {infected} | {scav} |')
    out += ['', f"Total: {len(encounters)} enemies, {sum(1 for e in encounters if e['kind'] == 'infected')} infected.", '']
    out += ['## Loot value by floor', '',
            'Expected value is computed analytically from each container\'s tier table and the existing `ItemDef.value` fields; loose sockets count at the active-socket fraction. Keycard-locked storage is reported separately and excluded from the baseline.', '',
            '| Building/level | Containers | Ransacked | Locked | Baseline value | Locked bonus | Loose |', '| --- | ---: | ---: | ---: | ---: | ---: | ---: |']
    for key, f in sorted(loot['floors'].items()):
        out.append(f"| {key} | {f['containers']} | {f['empty']} | {f['locked']} | {f['baseline']:.0f} | {f['locked_bonus']:.0f} | {f['loose']} |")
    out += ['', '| Lab level | Expected value (both labs) | Ratio | Target |', '| --- | ---: | ---: | ---: |']
    for level in '1234':
        out.append(f"| {level} | {loot['lab_floor_value'][level]:.0f} | {loot['lab_floor_ratio'][level]:.2f}x | {loot['targets'][level]:.1f}x |")
    out += ['', 'Items with no `value` set count as 0 and were not given artificial values: ' + ', '.join(f'`{i}`' for i in sorted(loot['zero_value_items'])) + '.', '']
    out += ['## Existing-asset reuse', '',
            f'{len(assets)} distinct existing assets, {sum(assets.values())} placements. No new models were created; procedural `p:` furniture is the campus author\'s existing office desk, chair and rack.', '',
            '| Library | Asset | Placements |', '| --- | --- | ---: |']
    names = {'m': 'MedTac detail', 'e': 'Environment catalog', 'd': 'District props', 'p': 'Campus procedural'}
    for key, count in sorted(assets.items(), key=lambda kv: (kv[0][0], -kv[1])):
        lib, ident = key.split(':', 1)
        label = f'{ident} {catalog.get(ident, "")}'.strip() if lib == 'e' else ident.replace('_', ' ')
        out.append(f'| {names.get(lib, lib)} | {label} | {count} |')
    out += ['', '## Validation summary', '', '| Measure | Value |', '| --- | --- |']
    for key in ['rooms', 'rooms_checked', 'doors', 'storage', 'loose_sockets', 'lights', 'enemies', 'infected', 'entities', 'navigation_polygons', 'longest_extraction_route_m']:
        value = validation.get(key)
        out.append(f'| {key.replace("_", " ")} | {value:.0f} |' if isinstance(value, float) else f'| {key.replace("_", " ")} | {value} |')
    out.append(f"| validation errors | {len(validation.get('errors', []))} |")
    (ROOT / 'docs/medtac-campus-reference.md').write_text('\n'.join(out) + '\n', encoding='utf-8')
    print('CAMPUS DOCS: docs/medtac-campus-reference.md')


if __name__ == '__main__':
    main()
